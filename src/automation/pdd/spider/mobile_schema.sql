CREATE SCHEMA IF NOT EXISTS ods;
CREATE TABLE IF NOT EXISTS ods.t_pdd_rankings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    capture_date TEXT NOT NULL,
    week_start TEXT NOT NULL,
    source_name TEXT NOT NULL,
    main_name TEXT NOT NULL,
    tab_name TEXT NOT NULL,
    source_url TEXT NOT NULL DEFAULT '',
    source_order BIGINT NOT NULL DEFAULT 0,
    tab_index BIGINT NOT NULL DEFAULT 0,
    description TEXT NOT NULL DEFAULT '',
    directory TEXT NOT NULL,
    state TEXT NOT NULL DEFAULT 'pending' CHECK (state IN ('unavailable','pending','running','completed','retry_pending')),
    created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'Asia/Shanghai', 'YYYY-MM-DD"T"HH24:MI:SS') || '+08:00'),
    updated_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'Asia/Shanghai', 'YYYY-MM-DD"T"HH24:MI:SS') || '+08:00'),
    UNIQUE(week_start, source_name, tab_name)
);
CREATE TABLE IF NOT EXISTS ods.t_pdd_ranking_products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ranking_id BIGINT NOT NULL REFERENCES ods.t_pdd_rankings(id) ON DELETE CASCADE,
    rank BIGINT NOT NULL CHECK(rank > 0),
    title TEXT NOT NULL DEFAULT '',
    platform_product_id TEXT NOT NULL DEFAULT '',
    platform_product_link TEXT NOT NULL DEFAULT '',
    listing_date TEXT,
    collection_month TEXT NOT NULL,
    collection_month_week BIGINT NOT NULL,
    collection_week_year BIGINT NOT NULL,
    collection_year_week BIGINT NOT NULL,
    display_price TEXT,
    recent_sales TEXT,
    total_sales TEXT,
    hot_index TEXT,
    dominance_days TEXT,
    positive_rate TEXT,
    positive_count TEXT,
    coupon_price TEXT,
    deal_price_30d TEXT,
    price_drop TEXT,
    directory TEXT NOT NULL,
    ranking_product_screenshot_state TEXT NOT NULL DEFAULT 'pending',
    product_screenshot_state TEXT NOT NULL DEFAULT 'pending',
    main_images_state TEXT NOT NULL DEFAULT 'pending',
    sku_state TEXT NOT NULL DEFAULT 'pending',
    detail_images_state TEXT NOT NULL DEFAULT 'pending',
    comments_state TEXT NOT NULL DEFAULT 'pending',
    created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'Asia/Shanghai', 'YYYY-MM-DD"T"HH24:MI:SS') || '+08:00'),
    updated_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'Asia/Shanghai', 'YYYY-MM-DD"T"HH24:MI:SS') || '+08:00'),
    UNIQUE(ranking_id, rank)
);
ALTER TABLE ods.t_pdd_rankings ADD COLUMN IF NOT EXISTS product_count BIGINT NOT NULL DEFAULT 0;
CREATE TABLE IF NOT EXISTS ods.t_pdd_product_skus (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ranking_product_id BIGINT NOT NULL REFERENCES ods.t_pdd_ranking_products(id) ON DELETE CASCADE,
    dedup_key TEXT NOT NULL,
    position BIGINT NOT NULL,
    specs_json TEXT NOT NULL DEFAULT '{}' CHECK(specs_json::jsonb IS NOT NULL),
    price TEXT,
    local_path TEXT,
    UNIQUE(ranking_product_id, dedup_key)
);
CREATE TABLE IF NOT EXISTS ods.t_pdd_product_main_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ranking_product_id BIGINT NOT NULL REFERENCES ods.t_pdd_ranking_products(id) ON DELETE CASCADE,
    position BIGINT NOT NULL CHECK(position > 0),
    local_path TEXT NOT NULL,
    state TEXT NOT NULL DEFAULT 'completed',
    UNIQUE(ranking_product_id, position)
);
CREATE TABLE IF NOT EXISTS ods.t_pdd_products_detail_image (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ranking_product_id BIGINT NOT NULL REFERENCES ods.t_pdd_ranking_products(id) ON DELETE CASCADE,
    position BIGINT NOT NULL CHECK(position > 0),
    local_path TEXT NOT NULL,
    state TEXT NOT NULL DEFAULT 'completed',
    UNIQUE(ranking_product_id, position)
);
CREATE TABLE IF NOT EXISTS ods.t_pdd_product_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ranking_product_id BIGINT NOT NULL REFERENCES ods.t_pdd_ranking_products(id) ON DELETE CASCADE,
    dedup_key TEXT NOT NULL,
    content TEXT NOT NULL DEFAULT '',
    sku_text TEXT,
    tag TEXT NOT NULL DEFAULT '',
    commented_at TEXT,
    collected_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'Asia/Shanghai', 'YYYY-MM-DD"T"HH24:MI:SS') || '+08:00'),
    UNIQUE(ranking_product_id, dedup_key)
);
CREATE TABLE IF NOT EXISTS ods.t_pdd_selling_point (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ranking_product_id BIGINT NOT NULL UNIQUE REFERENCES ods.t_pdd_ranking_products(id),
    platform_product_id TEXT NOT NULL,
    main_point TEXT NOT NULL,
    secondary_point TEXT NOT NULL,
    raw_json TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS ods.t_pdd_product_analysis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ranking_product_id BIGINT NOT NULL UNIQUE REFERENCES ods.t_pdd_ranking_products(id) ON DELETE CASCADE,
    match_state TEXT NOT NULL DEFAULT 'pending' CHECK (match_state IN ('pending','running','completed','failed')),
    match_result TEXT NOT NULL DEFAULT '',
    matched_product_id BIGINT REFERENCES ods.t_pdd_ranking_products(id) ON DELETE SET NULL,
    match_evidence JSONB NOT NULL DEFAULT '{}',
    image_signature TEXT NOT NULL DEFAULT '',
    history_signature TEXT NOT NULL DEFAULT '',
    point_state TEXT NOT NULL DEFAULT 'pending' CHECK (point_state IN ('pending','running','completed','failed')),
    last_error TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'Asia/Shanghai', 'YYYY-MM-DD"T"HH24:MI:SS') || '+08:00'),
    updated_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'Asia/Shanghai', 'YYYY-MM-DD"T"HH24:MI:SS') || '+08:00')
);

-- A previously completed ranking may still need the newly introduced analysis steps.
UPDATE ods.t_pdd_rankings r SET state='pending',
    updated_at=(to_char(clock_timestamp() AT TIME ZONE 'Asia/Shanghai', 'YYYY-MM-DD"T"HH24:MI:SS') || '+08:00')
WHERE r.state='completed' AND EXISTS (
    SELECT 1 FROM ods.t_pdd_ranking_products p
    WHERE p.ranking_id=r.id
    AND NOT (p.ranking_product_screenshot_state='skipped' OR p.product_screenshot_state='skipped'
        OR p.main_images_state='skipped' OR p.sku_state='skipped' OR p.detail_images_state='skipped' OR p.comments_state='skipped')
    AND (btrim(COALESCE(p.platform_product_id,''))=''
        OR btrim(COALESCE(p.platform_product_link,''))='' OR btrim(COALESCE(p.listing_date,''))=''
        OR NOT EXISTS(SELECT 1 FROM ods.t_pdd_selling_point sp WHERE sp.ranking_product_id=p.id))
);

CREATE OR REPLACE FUNCTION ods.t_pdd_selling_point_set_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at = clock_timestamp();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS t_pdd_selling_point_updated_at ON ods.t_pdd_selling_point;
CREATE TRIGGER t_pdd_selling_point_updated_at
    BEFORE UPDATE ON ods.t_pdd_selling_point
    FOR EACH ROW EXECUTE FUNCTION ods.t_pdd_selling_point_set_updated_at();

